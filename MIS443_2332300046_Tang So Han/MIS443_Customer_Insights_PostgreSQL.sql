BEGIN;

-- Allow the script to be rerun in a practice or testing database.
-- Child tables are removed before parent tables to respect foreign keys.
DROP TABLE IF EXISTS public.baskets;
DROP TABLE IF EXISTS public.orders;
DROP TABLE IF EXISTS public.products;
DROP TABLE IF EXISTS public.customers;
DROP TABLE IF EXISTS public.country;

-- -----------------------------------------------------------------------------
-- Table: country
-- Stores the countries in which orders are placed.
-- -----------------------------------------------------------------------------
CREATE TABLE public.country (
    country_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    country_name VARCHAR(50) NOT NULL,
    head_office  VARCHAR(50) NOT NULL,
    CONSTRAINT pk_country PRIMARY KEY (country_id),
    CONSTRAINT uq_country_name UNIQUE (country_name)
);

-- -----------------------------------------------------------------------------
-- Table: customers
-- Stores customer profile and marketing-permission information.
-- -----------------------------------------------------------------------------
CREATE TABLE public.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    first_shop  DATE NOT NULL,
    age         INTEGER NOT NULL,
    rewards     VARCHAR(3) NOT NULL,
    can_email   VARCHAR(3) NOT NULL,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT chk_customer_age CHECK (age BETWEEN 18 AND 120),
    CONSTRAINT chk_customer_rewards CHECK (rewards IN ('yes', 'no')),
    CONSTRAINT chk_customer_can_email CHECK (can_email IN ('yes', 'no'))
);

-- -----------------------------------------------------------------------------
-- Table: products
-- Stores product categories and current unit prices.
-- -----------------------------------------------------------------------------
CREATE TABLE public.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    category   VARCHAR(50) NOT NULL,
    price      NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT chk_product_price CHECK (price > 0)
);

-- -----------------------------------------------------------------------------
-- Table: orders
-- Stores each customer order and its sales channel and country.
-- -----------------------------------------------------------------------------
CREATE TABLE public.orders (
    order_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    customer_id   INTEGER NOT NULL,
    date_shop     DATE NOT NULL,
    sales_channel VARCHAR(20) NOT NULL,
    country_id    INTEGER NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES public.customers (customer_id),
    CONSTRAINT fk_orders_country
        FOREIGN KEY (country_id)
        REFERENCES public.country (country_id),
    CONSTRAINT chk_order_sales_channel
        CHECK (sales_channel IN ('retail', 'online'))
);

-- -----------------------------------------------------------------------------
-- Table: baskets
-- Stores the products and quantities included in each order.
-- One product can appear only once in an order; quantity records units purchased.
-- -----------------------------------------------------------------------------
CREATE TABLE public.baskets (
    order_id   INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity   INTEGER NOT NULL,
    CONSTRAINT pk_baskets PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_baskets_order
        FOREIGN KEY (order_id)
        REFERENCES public.orders (order_id),
    CONSTRAINT fk_baskets_product
        FOREIGN KEY (product_id)
        REFERENCES public.products (product_id),
    CONSTRAINT chk_basket_quantity CHECK (quantity > 0)
);

